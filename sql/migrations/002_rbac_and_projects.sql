alter table account.creds add column if not exists role smallint not null default 2;
alter table account.creds add column if not exists status smallint not null default 1;
alter table account.creds add column if not exists must_change_password boolean not null default false;
alter table account.creds add column if not exists temp_password_expires_at timestamptz;
alter table account.creds add column if not exists last_login_at timestamptz;
alter table account.creds add column if not exists createdAt timestamptz not null default now();

do $$
begin
    if not exists (select 1 from pg_constraint where conname = 'creds_role_check' and conrelid = 'account.creds'::regclass) then
        update account.creds set role = 1;
        alter table account.creds add constraint creds_role_check check (role in (1, 2));
    end if;
    if not exists (select 1 from pg_constraint where conname = 'creds_status_check' and conrelid = 'account.creds'::regclass) then
        alter table account.creds add constraint creds_status_check check (status in (1, 2));
    end if;
end
$$;

alter table account.creds alter column key_hash drop not null;
alter table account.creds alter column key_hint drop not null;

do $$
begin
    if not exists (
        select 1 from information_schema.columns
        where table_schema = 'account' and table_name = 'creds' and column_name = 'id' and is_identity = 'YES'
    ) then
        alter table account.creds alter column id add generated by default as identity;
        perform setval(pg_get_serial_sequence('account.creds', 'id'), coalesce((select max(id) from account.creds), 0) + 1, false);
    end if;
end
$$;

drop function if exists account.create(varchar, bytea, text, text);
drop function if exists account.set_password(int, bytea);
