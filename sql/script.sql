            outcode := 1;
            return;
        end if;
    else
        insert into account.project(slug, name, description, url, icon, status)
        values (p_slug, p_name, p_description, p_url, p_icon, p_status);
    end if;
    outcode := -1;
exception
    when unique_violation then
        outcode := 0;
    when others then
        raise warning 'DB Error: %', sqlerrm;
        outcode := 2;
end;
$$ language plpgsql security definer set search_path = '';

