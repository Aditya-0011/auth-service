create schema if not exists account;

create table if not exists account.creds (
    id int generated by default as identity primary key,
    email varchar(100) not null unique,
    password bytea not null,
    role smallint not null default 2 check (role in (1, 2)),
    status smallint not null default 1 check (status in (1, 2)),
    must_change_password boolean not null default false,
    temp_password_expires_at timestamptz,
    key_hash text unique,
    key_hint text,
    key_origins text[] not null default '{}',
    last_login_at timestamptz,
    createdAt timestamptz not null default now(),
    updatedAt timestamptz not null default now()
);

create table if not exists account.recovery_code (
    id int generated always as identity primary key,
    userId int not null,
    code_hash text not null unique,
    createdAt timestamptz not null default now()
);
create index if not exists idx_recovery_code_userId on account.recovery_code(userId);

create table if not exists account.project (
    id int generated always as identity primary key,
    slug varchar(50) not null unique check (slug ~ '^[a-z][a-z0-9-]{1,49}$'),
    name varchar(100) not null,
    description varchar(500) not null default '',
    url varchar(255) not null,
    icon varchar(32) not null default 'box',
    status smallint not null default 1 check (status in (1, 2, 3)),
    createdAt timestamptz not null default now(),
    updatedAt timestamptz not null default now()
);

create table if not exists account.project_access (
    userId int not null,
    projectId int not null,
    grantedAt timestamptz not null default now(),
    primary key (userId, projectId)
);
create index if not exists idx_project_access_projectId on account.project_access(projectId);

