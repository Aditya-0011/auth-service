create or replace function account.reset_password(
    in p_email varchar,
    in p_code_hash text,
    in p_password bytea,
    out id int,
    out outcode smallint)
as $$
begin
    select c.id into reset_password.id from account.creds c where lower(c.email) = lower(p_email) and c.status = 1 for update;
    if not found then
        id := 0;
        outcode := 1;
        return;
    end if;

    delete from account.recovery_code r where r.userId = reset_password.id and r.code_hash = p_code_hash;
    if not found then
        id := 0;
        outcode := 1;
        return;
    end if;

    update account.creds c
        set password = p_password,
            must_change_password = false,
            temp_password_expires_at = null,
            updatedAt = now()
        where c.id = reset_password.id;
    outcode := -1;
exception
    when others then
        raise warning 'DB Error: %', sqlerrm;
        id := 0;
        outcode := 2;
end;
$$ language plpgsql security definer set search_path = '';

create or replace function account.set_user_status(in p_id int, in p_status smallint, out outcode smallint)
as $$
