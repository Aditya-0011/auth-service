create or replace function account.set_user_projects(in p_id int, in p_project_ids int[], out outcode smallint)
as $$
declare
    v_role smallint;
    v_ids int[] := array(select distinct unnest(coalesce(p_project_ids, '{}'::int[])));
begin
    select c.role into v_role from account.creds c where c.id = p_id for update;
    if not found then
        outcode := 1;
        return;
    end if;
    if v_role = 1 then
        outcode := 3;
        return;
    end if;
    if not account.projects_exist(v_ids) then
        outcode := 1;
        return;
    end if;

    delete from account.project_access where userId = p_id and projectId <> all(v_ids);
    insert into account.project_access(userId, projectId)
    select p_id, pid from unnest(v_ids) as pid
    on conflict (userId, projectId) do nothing;

    outcode := -1;
exception
    when others then
        raise warning 'DB Error: %', sqlerrm;
        outcode := 2;
end;
$$ language plpgsql security definer set search_path = '';

