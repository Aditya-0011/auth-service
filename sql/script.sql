create or replace function account.complete_first_login(
    in p_id int,
    in p_password bytea,
    in p_code_hashes text[],
    out outcode smallint)
as $$
begin
    update account.creds
        set password = p_password,
            must_change_password = false,
            temp_password_expires_at = null,
            updatedAt = now()
        where id = p_id and status = 1 and must_change_password;
    if not found then
        outcode := 1;
        return;
    end if;

    delete from account.recovery_code where userId = p_id;
    insert into account.recovery_code(userId, code_hash)
    select p_id, h from unnest(p_code_hashes) as h;

    outcode := -1;
exception
    when others then
        raise warning 'DB Error: %', sqlerrm;
        outcode := 2;
end;
$$ language plpgsql security definer set search_path = '';

create or replace function account.can_use_api_key(in p_id int)
returns boolean
as $$
    select exists (
        select 1 from account.creds c
        where c.id = p_id and c.status = 1 and (
            c.role = 1 or exists (
                select 1 from account.project_access a
                join account.project p on p.id = a.projectId
                where a.userId = c.id and p.slug = 'manager' and p.status = 1
            )
        )
    );
$$ language sql stable security definer set search_path = '';

create or replace function account.rotate_key(
    in p_id int,
    in p_key_hash text,
    in p_key_hint text,
    out previous_key_hash text,
    out updated_at timestamptz,
    out outcode smallint)
as $$
begin
    if not account.can_use_api_key(p_id) then
        outcode := 3;
        return;
    end if;

    select c.key_hash into previous_key_hash from account.creds c where c.id = p_id for update;

    update account.creds
        set key_hash = p_key_hash, key_hint = p_key_hint, updatedAt = now()
        where id = p_id
        returning updatedAt into updated_at;

    outcode := -1;
exception
    when others then
        raise warning 'DB Error: %', sqlerrm;
        outcode := 2;
end;
$$ language plpgsql security definer set search_path = '';

