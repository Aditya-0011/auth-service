create or replace function account.edit_project(
    in p_id int,
    in p_slug varchar,
    in p_name varchar,
    in p_description varchar,
    in p_url varchar,
    in p_icon varchar,
    in p_status smallint,
    out outcode smallint)
as $$
begin
    if p_id > 0 then
        update account.project
            set slug = p_slug, name = p_name, description = p_description, url = p_url,
                icon = p_icon, status = p_status, updatedAt = now()
            where id = p_id;
