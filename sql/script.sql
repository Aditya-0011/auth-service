create or replace function account.projects_exist(in p_project_ids int[])
returns boolean
as $$
    select coalesce(array_length(p_project_ids, 1), 0) =
           (select count(*) from account.project p where p.id = any(p_project_ids));
$$ language sql stable security definer set search_path = '';

create or replace function account.create_user(
    in p_email varchar,
    in p_password bytea,
    in p_role smallint,
    in p_must_change boolean,
    in p_temp_expires timestamptz,
    in p_project_ids int[],
    out id int,
    out outcode smallint)
as $$
declare
    v_ids int[] := array(select distinct unnest(coalesce(p_project_ids, '{}'::int[])));
begin
    if not account.projects_exist(v_ids) then
        id := 0;
        outcode := 1;
        return;
    end if;

    insert into account.creds(email, password, role, must_change_password, temp_password_expires_at)
    values (p_email, p_password, p_role, p_must_change, p_temp_expires)
    returning creds.id into create_user.id;

    insert into account.project_access(userId, projectId)
    select create_user.id, pid from unnest(v_ids) as pid;

    outcode := -1;
exception
    when unique_violation then
        id := 0;
        outcode := 0;
    when others then
        raise warning 'DB Error: %', sqlerrm;
        id := 0;
        outcode := 2;
end;
$$ language plpgsql security definer set search_path = '';

